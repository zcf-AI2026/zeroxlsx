"""Build a small report with zeroxlsx — no dependencies, no external assets.

Run it:  python examples/make_demo.py
Output:  examples/demo.xlsx
"""

from __future__ import annotations

import struct
import zlib
from pathlib import Path

from zeroxlsx import Style, Workbook

HERE = Path(__file__).parent

BOLD = Style(bold=True)
HEADER = Style(bold=True, fill="#F2E8D5", h_align="center", v_align="center")
TITLE = Style(bold=True, size=14)
MONEY = Style(number_format="#,##0.00")
PERCENT = Style(number_format="0.0%")

ROWS = [
    ("North", 128, 48230.50, 0.312),
    ("South", 96, 35120.00, 0.284),
    ("East", 143, 51004.25, 0.335),
    ("West", 74, 22880.75, 0.271),
]


def make_logo(width: int = 96, height: int = 96) -> bytes:
    """A tiny solid-colour PNG, generated on the fly (no Pillow needed)."""

    def chunk(kind: bytes, data: bytes) -> bytes:
        return (len(data).to_bytes(4, "big") + kind + data
                + (zlib.crc32(kind + data) & 0xFFFFFFFF).to_bytes(4, "big"))

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    rows = b"".join(b"\x00" + b"\xA1\x44\x27" * width for _ in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b""))


def main() -> None:
    book = Workbook()
    sheet = book.add_sheet("Summary")

    # Row 1: a merged title. Excel keeps the content in the top-left cell.
    sheet.merge("A1:D1", "Quarterly summary", TITLE)

    # Row 2: header
    for column, label in enumerate(["Region", "Orders", "Revenue", "Margin"], start=1):
        sheet.write(2, column, label, HEADER)

    # Rows 3..6: one row per region, with per-cell formats
    first_row = 3
    for offset, (region, orders, revenue, margin) in enumerate(ROWS):
        row = first_row + offset
        sheet.write(row, 1, region)
        sheet.write(row, 2, orders)
        sheet.write(row, 3, revenue, MONEY)
        sheet.write(row, 4, margin, PERCENT)

    # Row 7: totals, the margin column is a real formula
    total_row = first_row + len(ROWS)
    last_data_row = total_row - 1
    sheet.write(total_row, 1, "Total", BOLD)
    sheet.write(total_row, 2, sum(item[1] for item in ROWS), BOLD)
    sheet.write(total_row, 3, sum(item[2] for item in ROWS), MONEY)
    sheet.write(total_row, 4, f"=SUM(D{first_row}:D{last_data_row})", PERCENT)

    # A generated logo floating next to the table (aspect ratio kept)
    sheet.add_image(make_logo(), anchor="F2", width=72)

    sheet.set_column_width("A", 14)
    sheet.set_column_width("B", 10)
    sheet.set_column_width("C", 14)
    sheet.set_column_width("D", 10)

    notes = book.add_sheet("Notes")
    notes.append(["Everything on these sheets is fabricated sample data."])
    notes.append(["The logo is generated by this script, not loaded from disk."])

    target = HERE / "demo.xlsx"
    book.save(target)
    print(f"wrote {target} ({target.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
